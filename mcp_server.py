"""MCP Server for Markdown Table AST Normalizer.
100% Python Standard Library JSON-RPC.
"""
import sys
import json
from client import MarkdownTableAstNormalizer

def main():
    while True:
        line = sys.stdin.readline()
        if not line:
            break
        try:
            req = json.loads(line)
            method = req.get("method")
            msg_id = req.get("id")

            if method == "tools/list":
                resp = {
                    "jsonrpc": "2.0",
                    "id": msg_id,
                    "result": {
                        "tools": [
                            {
                                "name": "parse_and_normalize",
                                "description": "Normalize misaligned Markdown table and export to clean CSV and JSON",
                                "inputSchema": {
                                    "type": "object",
                                    "properties": {
                                        "markdown_table": {"type": "string"}
                                    },
                                    "required": ["markdown_table"]
                                }
                            }
                        ]
                    }
                }
            elif method == "tools/call":
                args = req.get("params", {}).get("arguments", {})
                res = MarkdownTableAstNormalizer.parse_and_normalize(args.get("markdown_table", ""))
                resp = {
                    "jsonrpc": "2.0",
                    "id": msg_id,
                    "result": {"content": [{"type": "text", "text": json.dumps(res, indent=2)}]}
                }
            else:
                resp = {"jsonrpc": "2.0", "id": msg_id, "error": {"code": -32601, "message": "Method not found"}}
            sys.stdout.write(json.dumps(resp) + "\n")
            sys.stdout.flush()
        except Exception as e:
            sys.stdout.write(json.dumps({"jsonrpc": "2.0", "error": {"code": -32000, "message": str(e)}}) + "\n")
            sys.stdout.flush()

if __name__ == "__main__":
    main()
